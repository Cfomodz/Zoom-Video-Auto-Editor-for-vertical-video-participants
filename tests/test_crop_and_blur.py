class TestEdgeCases:
    """Edge cases for pillarbox_content_bounds with various bar widths."""

    def _make_frame(self, w, h, left_bar, right_bar, content_val=200):
        """Create a frame with specified bar widths."""
        frame = np.zeros((h, w, 3), dtype=np.uint8)
        frame[:, left_bar:w - right_bar, :] = content_val
        return frame

    def test_wide_bars_detected(self):
        """Bars wider than min_bar should be fully detected, not truncated at min_bar."""
        frame = self._make_frame(1920, 1080, left_bar=400, right_bar=400)
        bounds = pillarbox_content_bounds(frame)
        assert bounds is not None
        x_left, x_right = bounds
        tolerance = PILLAR_EDGE_WINDOW + 1
        assert abs(x_left - 400) <= tolerance, f"Left bound {x_left} should be near 400"
        assert abs(x_right - 1520) <= tolerance, f"Right bound {x_right} should be near 1520"

    def test_asymmetric_bars(self):
        """Asymmetric bars: wider left bar than right bar."""
        frame = self._make_frame(1920, 1080, left_bar=500, right_bar=200)
        bounds = pillarbox_content_bounds(frame)
        assert bounds is not None
        x_left, x_right = bounds
        tolerance = PILLAR_EDGE_WINDOW + 1
        assert abs(x_left - 500) <= tolerance, f"Left bound {x_left} should be near 500"
        assert abs(x_right - 1720) <= tolerance, f"Right bound {x_right} should be near 1720"

    def test_very_narrow_bars_rejected(self):
        """Bars thinner than min_bar (5% of width) should not trigger detection."""
        # min_bar for 1920 = 96. Use 50px bars — too thin.
        frame = self._make_frame(1920, 1080, left_bar=50, right_bar=50)
        bounds = pillarbox_content_bounds(frame)
        assert bounds is None, "Bars thinner than PILLAR_MIN_WIDTH_RATIO should be rejected"

    def test_all_black_frame(self):
        """A fully black frame should return None (no content to detect)."""
        frame = np.zeros((1080, 1920, 3), dtype=np.uint8)
        bounds = pillarbox_content_bounds(frame)
        assert bounds is None

    def test_left_bar_only(self):
        """Only a left bar (no right bar) should return None (requires both bars)."""
        frame = np.full((1080, 1920, 3), 150, dtype=np.uint8)
        frame[:, :400, :] = 0  # left bar only
        bounds = pillarbox_content_bounds(frame)
        assert bounds is None, "Should require both bars"

    def test_right_bar_only(self):
        """Only a right bar (no left bar) should return None."""
        frame = np.full((1080, 1920, 3), 150, dtype=np.uint8)
        frame[:, 1520:, :] = 0  # right bar only
        bounds = pillarbox_content_bounds(frame)
        assert bounds is None, "Should require both bars"
