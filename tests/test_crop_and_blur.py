class TestIsBlackColumn:
    """Unit tests for the windowed is_black_column helper."""

    def test_pure_black_column(self):
        frame = np.zeros((100, 200, 3), dtype=np.uint8)
        assert is_black_column(frame, 50)

    def test_bright_column(self):
        frame = np.full((100, 200, 3), 200, dtype=np.uint8)
        assert not is_black_column(frame, 50)

    def test_mixed_frame_black_region(self):
        frame = np.full((100, 200, 3), 200, dtype=np.uint8)
        # Make columns 0-49 black
        frame[:, :50, :] = 0
        # Column 10 is deep inside black region, should be black
        assert is_black_column(frame, 10, window=5)

    def test_mixed_frame_bright_region(self):
        frame = np.full((100, 200, 3), 200, dtype=np.uint8)
        frame[:, :50, :] = 0
        # Column 150 is deep inside bright region
        assert not is_black_column(frame, 150, window=5)


