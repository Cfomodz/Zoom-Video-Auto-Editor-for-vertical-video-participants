# 3. Blur-fill tests
# ---------------------------------------------------------------------------

class TestBlurFill:
    """blur_fill_cropped_frame should produce 1920x1080 with no black columns."""

    def test_output_dimensions(self):
        frame = _load(PILLARBOXED_IMG)
        x_left, x_right = pillarbox_content_bounds(frame)
        cropped = frame[:, x_left:x_right, :]
        filled = blur_fill_cropped_frame(cropped)
        assert filled.shape == (OUTPUT_HEIGHT, OUTPUT_WIDTH, 3)

    def test_no_black_columns_in_output(self):
        """After blur-fill, every column should have non-zero mean (blurred background, not black)."""
        frame = _load(PILLARBOXED_IMG)
        x_left, x_right = pillarbox_content_bounds(frame)
        cropped = frame[:, x_left:x_right, :]
        filled = blur_fill_cropped_frame(cropped)
        col_means = column_means(filled)
        # No column should be black (mean 0)
        assert col_means.min() > 0, (
            f"Column {col_means.argmin()} has mean 0 in blur-filled output"
        )
        # Stronger: no column should be near-black (the blur should spread color everywhere)
        assert col_means.min() > 5, (
            f"Column {col_means.argmin()} has very low mean {col_means.min():.1f} "
            f"in blur-filled output"
        )

    def test_edges_are_blurred(self):
        """The edge regions (blur background) should have lower high-frequency energy
        than the center region (sharp content), verified via Laplacian variance."""
        frame = _load(PILLARBOXED_IMG)
        x_left, x_right = pillarbox_content_bounds(frame)
        cropped = frame[:, x_left:x_right, :]
        filled = blur_fill_cropped_frame(cropped)
        gray = cv2.cvtColor(filled, cv2.COLOR_BGR2GRAY)
        lap = cv2.Laplacian(gray, cv2.CV_64F)

        center_var = lap[:, OUTPUT_WIDTH // 4 : 3 * OUTPUT_WIDTH // 4].var()
        left_edge_var = lap[:, :100].var()
        right_edge_var = lap[:, -100:].var()
        edge_var = (left_edge_var + right_edge_var) / 2

        assert center_var > edge_var, (
            f"Center Laplacian variance ({center_var:.2f}) should exceed "
            f"edge variance ({edge_var:.2f}); edges should be blurred"
        )

    def test_blur_fill_frame_direct(self):
        """blur_fill_frame (takes raw pillarboxed frame) should also produce valid output."""
        frame = _load(PILLARBOXED_IMG)
        filled = blur_fill_frame(frame)
        assert filled.shape == (OUTPUT_HEIGHT, OUTPUT_WIDTH, 3)
        col_means = column_means(filled)
        assert col_means.min() > 0, "No column should be pure black"

    def test_no_black_rows_in_output(self):
        """No row in the blur-filled output should be fully black either."""
        frame = _load(PILLARBOXED_IMG)
        x_left, x_right = pillarbox_content_bounds(frame)
        cropped = frame[:, x_left:x_right, :]
        filled = blur_fill_cropped_frame(cropped)
        row_means = filled.mean(axis=(1, 2))  # per-row mean
        assert row_means.min() > 0, (
            f"Row {row_means.argmin()} has mean 0 in blur-filled output"
        )


